const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const basePath = path.join(root, "data", "words.js");
const seedsPath = path.join(root, "data", "seeds.js");

const src = fs.readFileSync(basePath, "utf8");
const raw = [...src.matchAll(/"([^"]*)"/g)].map((m) => m[1]);

// data/seeds.js tops up the categories the legacy list left thin. Seeds are
// authoritative for their own bucket: re-running the keyword rules on them
// would dump most of them into "general", which is the imbalance we are fixing.
const seeds = fs.existsSync(seedsPath) ? require(seedsPath).SEEDS ?? {} : {};
const seedCount = Object.values(seeds).reduce((a, b) => a + b.length, 0);

// ---- normalize ----
const norm = (s) =>
  s
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s+/g, " ")
    .trim();

// ---- category rules, order matters (first match wins) ----
const RULES = [
  ["pets", /\b(dog|cat|pet|puppy|kitten|canine|feline)\w*\b/i],
  ["automotive", /\b(car|suv|sedan|motorcycle|truck|vehicle|tire|engine|gearbox|driving|tesla|jeep|ford|toyota|honda)\w*\b/i],
  ["cooking", /\b(recipe|cook|bake|baking|dessert|cake|coffee|tea|smoothie|vegan|vegetarian|meal|kitchen|sourdough|pasta|grill|spice|food)\w*\b/i],
  ["health", /\b(health|fitness|workout|yoga|meditation|sleep|diet|nutrition|exercise|muscle|mental health|doctor|dental|skincare)\w*\b/i],
  ["home", /\b(home|house|garden|furniture|diy|decor|cleaning|organization|storage|renovat)\w*\b/i],
  ["tech", /\b(coding|programming|python|javascript|software|computer|laptop|gadget|tech|ai|artificial intelligence|developer|web)\w*\b/i],
  ["travel", /\b(travel|trip|vacation|flight|hotel|city|beach|mountain|abroad|japan|italy|itinerary)\w*\b/i],
  ["finance", /\b(invest|stock|crypto|tax|finance|retire|budget|saving|insurance|mortgage|loan)\w*\b/i],
  ["education", /\b(learn|study|school|university|course|english|spanish|language|math|read|book|certificate)\w*\b/i],
  ["entertainment", /\b(movie|film|music|song|album|series|game|gaming|netflix|comic|anime|book|podcast)\w*\b/i],
];

function classify(w) {
  for (const [cat, re] of RULES) if (re.test(w)) return cat;
  return "general";
}

const seen = new Map();
const buckets = new Map();
let droppedLong = 0;
let droppedShort = 0;

function add(word, cat) {
  const w = norm(word);
  if (w.length < 10) { droppedShort++; return; }
  if (w.length > 60) { droppedLong++; return; } // reads as SEO spam
  const key = w.toLowerCase();
  if (seen.has(key)) return;
  seen.set(key, true);
  if (!buckets.has(cat)) buckets.set(cat, []);
  buckets.get(cat).push(w);
}

// Base list: category comes from the keyword rules.
for (const item of raw) add(item, classify(item));

// Seeds: category is declared, not inferred.
for (const [cat, words] of Object.entries(seeds)) {
  for (const w of words) add(w, cat);
}

for (const [, arr] of buckets) arr.sort((a, b) => a.localeCompare(b, "en"));

const order = [...RULES.map((r) => r[0]), ...Object.keys(seeds), "general"]
  .filter((c, i, a) => a.indexOf(c) === i);
const sorted = order.filter((c) => buckets.has(c));

const total = [...buckets.values()].reduce((a, b) => a + b.length, 0);

const body = sorted
  .map((cat) => `  ${cat}: [\n${buckets.get(cat).map((w) => `    ${JSON.stringify(w)},`).join("\n")}\n  ],`)
  .join("\n");

const out = `// AUTO-GENERATED by tools/build-keywords.js - do not edit by hand.
// Sources: data/words.js (legacy flat list) + data/seeds.js (category top-ups).
// Regenerate with: npm run build:keywords
//
// Normalisation applied: smart-quote folding, whitespace collapse, trim,
// case-insensitive dedupe, length band 10-60 chars.

export const CATEGORIES = ${JSON.stringify(sorted)};

export const KEYWORDS = {
${body}
};

export default KEYWORDS;
`;

fs.writeFileSync(path.join(root, "data", "keywords.js"), out);

const input = raw.length + seedCount;
console.log(`input     ${input}  (${raw.length} base + ${seedCount} seeds)`);
console.log(`kept      ${total}`);
console.log(`dupes     ${input - seen.size - droppedLong - droppedShort}`);
console.log(`too long  ${droppedLong}`);
console.log(`too short ${droppedShort}`);
console.log("");
for (const c of sorted) {
  const n = buckets.get(c).length;
  const pct = ((n / total) * 100).toFixed(1);
  console.log(`  ${c.padEnd(13)} ${String(n).padStart(4)}  ${pct.padStart(5)}%`);
}
